CREATE TABLE IF NOT EXISTS public.assembly_budgets (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  neighborhood_id BIGINT NOT NULL REFERENCES public.neighborhoods(id) ON DELETE CASCADE,
  fiscal_year INTEGER NOT NULL,
  category_id BIGINT NOT NULL REFERENCES public.assembly_categories(id) ON DELETE CASCADE,
  budget_amount NUMERIC DEFAULT 0,
  previous_budget_amount NUMERIC DEFAULT 0,
  note TEXT,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

