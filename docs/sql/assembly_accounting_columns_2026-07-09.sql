CREATE UNIQUE INDEX IF NOT EXISTS assembly_budgets_neighborhood_year_category_unique
  ON public.assembly_budgets (neighborhood_id, fiscal_year, category_id);

CREATE TABLE IF NOT EXISTS public.assembly_settlements (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  neighborhood_id BIGINT NOT NULL REFERENCES public.neighborhoods(id) ON DELETE CASCADE,
  fiscal_year INTEGER NOT NULL,
  category_id BIGINT REFERENCES public.assembly_categories(id) ON DELETE SET NULL,
  type TEXT NOT NULL CHECK (type IN ('income', 'expense')),
  amount NUMERIC DEFAULT 0,
  paid_date DATE,
  description TEXT,
  receipt_url TEXT,
  receipt_name TEXT,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

ALTER TABLE public.assembly_settlements
