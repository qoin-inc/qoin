DROP POLICY IF EXISTS neighborhood_fee_settings_select_members
ON public.neighborhood_fee_settings;
CREATE POLICY neighborhood_fee_settings_select_members
  ON public.neighborhood_fee_settings
  FOR SELECT
  TO authenticated
  USING (
    public.is_el_town_system_admin()
    OR neighborhood_id IN (
      SELECT admins.neighborhood_id
      FROM public.neighborhood_admins AS admins
      WHERE admins.admin_auth_id::TEXT = auth.uid()::TEXT
        AND admins.status = 'active'
    )
    OR neighborhood_id IN (
      SELECT rosters.neighborhood_id
      FROM public.resident_rosters AS rosters
      WHERE rosters.user_auth_id::TEXT = auth.uid()::TEXT
         OR rosters.family_user_auth_id_1::TEXT = auth.uid()::TEXT
         OR rosters.family_user_auth_id_2::TEXT = auth.uid()::TEXT
    )
  );

DROP POLICY IF EXISTS neighborhood_fee_settings_write_active_admins
ON public.neighborhood_fee_settings;
CREATE POLICY neighborhood_fee_settings_write_active_admins
  ON public.neighborhood_fee_settings
  FOR ALL
  TO authenticated
  USING (
    neighborhood_id IN (
      SELECT admins.neighborhood_id
      FROM public.neighborhood_admins AS admins
      WHERE admins.admin_auth_id::TEXT = auth.uid()::TEXT
        AND admins.status = 'active'
    )
  )
  WITH CHECK (
    neighborhood_id IN (
      SELECT admins.neighborhood_id
      FROM public.neighborhood_admins AS admins
      WHERE admins.admin_auth_id::TEXT = auth.uid()::TEXT
        AND admins.status = 'active'
    )
  );

