-- 町内会・自治会 会費標準設定
-- Supabase SQL Editorで本番DBへ適用する。
-- 既存のfee_records（請求・入金実績）は更新しない。

CREATE OR REPLACE FUNCTION public.is_el_town_system_admin()
RETURNS BOOLEAN
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public, auth
AS $$
  SELECT COALESCE(lower(auth.jwt() ->> 'email') = lower('admin@el-town.jp'), false);
$$;

REVOKE ALL ON FUNCTION public.is_el_town_system_admin() FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.is_el_town_system_admin() TO authenticated;

CREATE TABLE IF NOT EXISTS public.membership_fee_standard_versions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  version_number INTEGER NOT NULL UNIQUE CHECK (version_number > 0),
  status TEXT NOT NULL DEFAULT 'draft' CHECK (status IN ('draft', 'published', 'retired')),
  fee_name TEXT NOT NULL DEFAULT '年会費',
  default_amount INTEGER NOT NULL DEFAULT 3000 CHECK (default_amount >= 0),
  fiscal_year_start_month INTEGER NOT NULL DEFAULT 4 CHECK (fiscal_year_start_month BETWEEN 1 AND 12),
  billing_frequency TEXT NOT NULL DEFAULT 'annual' CHECK (billing_frequency IN ('annual')),
  billing_target TEXT NOT NULL DEFAULT 'active_households' CHECK (billing_target IN ('active_households')),
  cash_enabled BOOLEAN NOT NULL DEFAULT TRUE,
  stripe_card_enabled BOOLEAN NOT NULL DEFAULT TRUE,
  revenue_category TEXT NOT NULL DEFAULT '会費',
  change_reason TEXT NOT NULL,
  created_by UUID REFERENCES auth.users(id) ON DELETE SET NULL DEFAULT auth.uid(),
  published_at TIMESTAMP WITH TIME ZONE,
  retired_at TIMESTAMP WITH TIME ZONE,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW()
);

CREATE UNIQUE INDEX IF NOT EXISTS membership_fee_standard_one_published_idx
  ON public.membership_fee_standard_versions ((status))
  WHERE status = 'published';

CREATE TABLE IF NOT EXISTS public.neighborhood_fee_settings (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  neighborhood_id BIGINT NOT NULL UNIQUE REFERENCES public.neighborhoods(id) ON DELETE CASCADE,
  standard_version_id BIGINT REFERENCES public.membership_fee_standard_versions(id) ON DELETE SET NULL,
  fee_name TEXT NOT NULL DEFAULT '年会費',
  amount INTEGER NOT NULL DEFAULT 3000 CHECK (amount >= 0),
  fiscal_year_start_month INTEGER NOT NULL DEFAULT 4 CHECK (fiscal_year_start_month BETWEEN 1 AND 12),
  billing_frequency TEXT NOT NULL DEFAULT 'annual' CHECK (billing_frequency IN ('annual')),
  billing_target TEXT NOT NULL DEFAULT 'active_households' CHECK (billing_target IN ('active_households')),
  cash_enabled BOOLEAN NOT NULL DEFAULT TRUE,
  stripe_card_enabled BOOLEAN NOT NULL DEFAULT TRUE,
  revenue_category TEXT NOT NULL DEFAULT '会費',
  overridden_fields JSONB NOT NULL DEFAULT '{}'::JSONB,
  applied_at TIMESTAMP WITH TIME ZONE,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS neighborhood_fee_settings_standard_version_idx
  ON public.neighborhood_fee_settings(standard_version_id);

CREATE TABLE IF NOT EXISTS public.membership_fee_standard_applications (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  standard_version_id BIGINT NOT NULL REFERENCES public.membership_fee_standard_versions(id) ON DELETE RESTRICT,
  neighborhood_id BIGINT NOT NULL REFERENCES public.neighborhoods(id) ON DELETE CASCADE,
  before_settings JSONB,
  after_settings JSONB NOT NULL,
  application_type TEXT NOT NULL CHECK (application_type IN ('new_neighborhood', 'initial_backfill', 'manual')),
  applied_by UUID REFERENCES auth.users(id) ON DELETE SET NULL DEFAULT auth.uid(),
  applied_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS membership_fee_standard_applications_lookup_idx
  ON public.membership_fee_standard_applications(neighborhood_id, applied_at DESC);

CREATE OR REPLACE FUNCTION public.set_membership_fee_updated_at()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  NEW.updated_at = NOW();
  RETURN NEW;
END;
$$;

