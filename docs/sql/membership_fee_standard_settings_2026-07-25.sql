CREATE OR REPLACE FUNCTION public.publish_membership_fee_standard(p_version_id BIGINT)
RETURNS public.membership_fee_standard_versions
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, auth
AS $$
DECLARE
  published_version public.membership_fee_standard_versions;
BEGIN
  IF NOT public.is_el_town_system_admin() THEN
    RAISE EXCEPTION 'Only the el-town system administrator can publish membership fee standards.';
  END IF;

  IF NOT EXISTS (
    SELECT 1
    FROM public.membership_fee_standard_versions
    WHERE id = p_version_id
      AND status = 'draft'
  ) THEN
    RAISE EXCEPTION 'The requested draft membership fee standard was not found.';
  END IF;

  UPDATE public.membership_fee_standard_versions
  SET status = 'retired',
      retired_at = NOW()
  WHERE status = 'published';

  UPDATE public.membership_fee_standard_versions
  SET status = 'published',
      published_at = NOW(),
      retired_at = NULL
  WHERE id = p_version_id
  RETURNING * INTO published_version;

  RETURN published_version;
END;
$$;

REVOKE ALL ON FUNCTION public.publish_membership_fee_standard(BIGINT) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.publish_membership_fee_standard(BIGINT) TO authenticated;

CREATE OR REPLACE FUNCTION public.copy_published_membership_fee_standard()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, auth
AS $$
DECLARE
  standard public.membership_fee_standard_versions;
  inserted_setting public.neighborhood_fee_settings;
BEGIN
  SELECT *
    INTO standard
  FROM public.membership_fee_standard_versions
  WHERE status = 'published'
  ORDER BY version_number DESC
  LIMIT 1;

  IF standard.id IS NULL THEN
    RETURN NEW;
  END IF;

  INSERT INTO public.neighborhood_fee_settings (
    neighborhood_id,
    standard_version_id,
    fee_name,
    amount,
    fiscal_year_start_month,
    billing_frequency,
    billing_target,
    cash_enabled,
    stripe_card_enabled,
    revenue_category,
    applied_at
  )
  VALUES (
    NEW.id,
    standard.id,
    standard.fee_name,
    standard.default_amount,
    standard.fiscal_year_start_month,
    standard.billing_frequency,
    standard.billing_target,
    standard.cash_enabled,
    standard.stripe_card_enabled,
    standard.revenue_category,
    NOW()
  )
  ON CONFLICT (neighborhood_id) DO NOTHING
  RETURNING * INTO inserted_setting;

  IF inserted_setting.id IS NOT NULL THEN
    INSERT INTO public.membership_fee_standard_applications (
      standard_version_id,
      neighborhood_id,
      before_settings,
      after_settings,
      application_type
    )
    VALUES (
      standard.id,
      NEW.id,
      NULL,
      to_jsonb(inserted_setting),
      'new_neighborhood'
    );
  END IF;

  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS neighborhoods_copy_membership_fee_standard
ON public.neighborhoods;
CREATE TRIGGER neighborhoods_copy_membership_fee_standard
AFTER INSERT ON public.neighborhoods
FOR EACH ROW
EXECUTE FUNCTION public.copy_published_membership_fee_standard();

