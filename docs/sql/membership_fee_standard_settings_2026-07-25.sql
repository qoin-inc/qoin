WITH standard AS (
  SELECT *
  FROM public.membership_fee_standard_versions
  WHERE status = 'published'
  ORDER BY version_number DESC
  LIMIT 1
),
inserted AS (
  INSERT INTO public.neighborhood_fee_settings (
    neighborhood_id,
    standard_version_id,
    fee_name,
    amount,
    fiscal_year_start_month,
    billing_frequency,
    billing_target,
    cash_enabled,
    stripe_card_enabled,
    revenue_category,
    applied_at
  )
  SELECT
    neighborhoods.id,
    standard.id,
    standard.fee_name,
    standard.default_amount,
    standard.fiscal_year_start_month,
    standard.billing_frequency,
    standard.billing_target,
    standard.cash_enabled,
    standard.stripe_card_enabled,
    standard.revenue_category,
    NOW()
  FROM public.neighborhoods AS neighborhoods
  CROSS JOIN standard
  WHERE NOT EXISTS (
    SELECT 1
    FROM public.neighborhood_fee_settings AS existing
    WHERE existing.neighborhood_id = neighborhoods.id
  )
  RETURNING *
)
INSERT INTO public.membership_fee_standard_applications (
  standard_version_id,
  neighborhood_id,
  before_settings,
  after_settings,
  application_type
)
SELECT
  inserted.standard_version_id,
  inserted.neighborhood_id,
  NULL,
  to_jsonb(inserted),
  'initial_backfill'
FROM inserted;

